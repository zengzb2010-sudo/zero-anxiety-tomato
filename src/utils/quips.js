// 按时长适配（分钟）
const SHORT_RUNNING = ['碎片时间也是时间，接住它', '十分钟也能有个小突破']
const LONG_RUNNING = ['长跑选手，稳住', '这场耐力赛，你赢面很大']

/**
 * 取一条随机碎碎念
 * @param {string} kind 场景 key（见 POOLS）
 * @param {object} vars { subject, minutes, elapsed }
 */
export function quip(kind, { subject = '', minutes = 0, elapsed = '' } = {}) {
  let pool = POOLS[kind] || POOLS.idle
  if (kind === 'running') {
    // 时长适配 + 科目专属梗
    if (minutes > 0 && minutes <= 20) pool = [...pool, ...SHORT_RUNNING]
    if (minutes >= 60) pool = [...pool, ...LONG_RUNNING]
    const sub = SUBJECT_RUNNING[subject]
    if (sub) pool = [...pool, ...sub]
  }
  const t = pool[Math.floor(Math.random() * pool.length)]
  return t.replaceAll('{subject}', subject || '这门课').replaceAll('{elapsed}', elapsed || '这段时间')
}